// In-memory cache across renders so switching back and forth is instantaneous
const translationMemoryCache = new Map();

const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    return UI_STRINGS[saved] ? saved : 'vi';
  });

  const setLang = useCallback((nextLang) => {
    if (!UI_STRINGS[nextLang]) return;
    localStorage.setItem(LANG_STORAGE_KEY, nextLang);
    document.documentElement.lang = nextLang;
    setLangState(nextLang);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const t = useCallback(
    (key) => UI_STRINGS[lang]?.[key] ?? UI_STRINGS.vi[key] ?? key,
    [lang]
  );

  const tGenre = useCallback(
    (genreName) => {
      if (lang === 'en') return genreName;
      return GENRE_TRANSLATIONS[lang]?.[genreName] || genreName;
    },
    [lang]
  );

  const formatRuntime = useCallback(
    (minutes) => `${minutes || 0} ${UI_STRINGS[lang]?.runtimeUnit || 'phút'}`,
    [lang]
  );

  return (
    <LanguageContext.Provider value={{ lang, setLang, t, tGenre, formatRuntime, languages: LANGUAGES }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useLanguage must be used inside LanguageProvider');
  return ctx;
}

/**
 * Automatically resolves and caches translated movie synopsis for the active UI language.
 */
export function useTranslatedOverview(movie) {
  const { lang } = useLanguage();
  const [translated, setTranslated] = useState('');
  const [translating, setTranslating] = useState(false);
  const [showOriginal, setShowOriginal] = useState(false);

  const movieId = movie?.id;
  const original = movie?.overview || '';
  const embedded = movie?.overview_i18n?.[lang] || '';

  useEffect(() => {
    setShowOriginal(false);
    if (!movieId || !original || lang === 'en') {
      setTranslated(original);
      setTranslating(false);
      return;
    }

    const cacheKey = `${movieId}:${lang}`;
    if (embedded) {
      translationMemoryCache.set(cacheKey, embedded);
      setTranslated(embedded);
      setTranslating(false);
      return;
    }

    if (translationMemoryCache.has(cacheKey)) {
      setTranslated(translationMemoryCache.get(cacheKey));
      setTranslating(false);
      return;
    }

    let cancelled = false;
    setTranslated(original);
    setTranslating(true);
    api
      .translateMovie(movieId, lang)
      .then((res) => {
        if (cancelled) return;
        const text = res?.overview || original;
        translationMemoryCache.set(cacheKey, text);
        setTranslated(text);
      })
      .catch(() => {
        if (!cancelled) setTranslated(original);
      })
      .finally(() => {
        if (!cancelled) setTranslating(false);
      });

    return () => {
      cancelled = true;
    };
  }, [movieId, original, embedded, lang]);

  return {
    text: showOriginal || lang === 'en' ? original : translated || original,
    translating,
    canToggleOriginal: lang !== 'en' && Boolean(translated) && translated !== original,
    showOriginal,
    toggleOriginal: () => setShowOriginal((v) => !v),
  };
}
